DATA1 SEGMENT
    VAR1 DW 1111H
    FAR_PTR DW OFFSET VAR2, DATA2
DATA1 ENDS

DATA2 SEGMENT
    VAR2 DW 2222H
DATA2 ENDS

CODE SEGMENT
    ASSUME CS:CODE, DS:DATA1

START:
    MOV AX, DATA1
    MOV DS, AX

    ; 此时DS指向DATA1

    LDS SI, DWORD PTR FAR_PTR

    ; 此时DS指向DATA2
    ; SI指向VAR2

    MOV AX, [SI]

    MOV AH, 4CH
    INT 21H

    ; LDS：DS段寄存器
    ; LES：ES段寄存器
CODE ENDS
END START